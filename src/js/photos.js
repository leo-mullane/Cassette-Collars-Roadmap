/* ==========================================================================
   photos.js — Cassette Collars photography for the design layer (phase 3)

   Swaps illustrated placeholders for Cassette Collars' own photography,
   loaded directly from cassettecollars.co.uk. Any element with a
   data-photo="key" attribute gets the matching image as a background, but
   only once the image has loaded, so anywhere the images can't be reached
   the illustrated placeholder stays in place.

   Photography © Cassette Collars, used here to show how the proposals would
   look on the live site. Drawings, diagrams, logos and the rating-plate and
   portrait placeholders stay illustrated because there is no photo to use.
   Stock and AI-generated images on the live site are deliberately not used.
   ========================================================================== */

(function () {
  'use strict';

  var BASE = 'https://cassettecollars.co.uk/wp-content/uploads/';
  function u(path) { return BASE + path; }

  var P = {
    hero: u('2025/09/Cassette-collars-air-deflectors-air-conditioning.webp'),       // restaurant, live homepage hero
    collarClose: u('2025/09/1000x1000x30-cassette-collars-uk-air-condition-air-flow.webp'),
    collarOffice: u('2025/09/100x1000x110mmnewcollar4-cassette-collars-uk-air-condition-air-flow.webp'),
    collar1200: u('2025/09/1200x1200x2003-cassette-collars-air-conditioning-uk-deflectors-air-flow.webp'),
    collarCeiling: u('2025/09/howtodoit2-cassette-collars-uk-air-conditioner-air-flow.webp'),
    collarWall: u('2025/09/air-deflector-cassette-collars-uk-air-conditioning.webp'),
    officeFlow1: u('2025/09/cassette-collars-air-deflectors-air-conditioner-uk-flow-1.webp'),
    officeFlow2: u('2025/09/cassette-collars-air-deflectors-air-conditioner-uk-flow-2.webp'),
    deflectorOffice: u('2020/09/22ae5507-cc60-46c5-a6be-fc490c3cd4bc.jpg'),
    deflectorCeiling: u('2020/09/b1cad2da-503b-45cc-a144-dfe31077fb39.jpg'),
    quality: u('2026/10/cassette-collars-uk-air-deflectors-air-conditioner-flow-quality.webp'),
    cooling: u('2026/10/cassette-collars-uk-air-conditioner-deflectors-cooling.webp'),
    flowWide: u('2026/10/ac-air-deflector-cassette-collar-uk-conditioning-flow-conditioner-.webp'),
    size: u('2026/10/ac-air-deflector-cassette-collar-uk-conditioning-size.webp'),
    flow: u('2026/10/ac-air-deflector-cassette-collar-uk-conditioning-flow.webp'),
    angled: u('2025/09/ac-air-deflector-cassette-collar-uk-conditioning.webp')
  };

  /* Keys used in the pages (and in markup generated by wireframe.js). */
  var MAP = {
    'hero': P.hero,
    'thumb-finder': P.angled,
    'thumb-quote': P.flowWide,
    'thumb-product': P.collarClose,
    'thumb-colours': P.collarWall,
    'thumb-projects': P.deflectorCeiling,
    'collar-650': P.collarClose,
    'collar-750': P.size,
    'collar-850': P.quality,
    'collar-1000': P.collarOffice,
    'collar-1200': P.collar1200,
    'gallery-1': P.officeFlow2,
    'gallery-2': P.collarCeiling,
    'gallery-3': P.cooling,
    'deflector': P.deflectorCeiling,
    'project-p1': P.hero,
    'project-p2': P.deflectorCeiling,
    'project-p3': P.collarCeiling,
    'project-p4': P.size,
    'project-p5': P.flowWide,
    'project-p6': P.deflectorOffice,
    'project-p7': P.officeFlow1,
    'project-p8': P.angled,
    'project-p9': P.collarOffice
  };

  var cache = {};
  function load(src, done) {
    if (cache[src] === true) { done(true); return; }
    if (cache[src] === false) { done(false); return; }
    var img = new Image();
    img.onload = function () { cache[src] = true; done(true); };
    img.onerror = function () { cache[src] = false; done(false); };
    img.src = src;
  }

  function apply(el) {
    var key = el.getAttribute('data-photo');
    var src = MAP[key];
    if (!src || el.getAttribute('data-photo-done') === key) return;
    el.setAttribute('data-photo-done', key);
    load(src, function (ok) {
      if (!ok || el.getAttribute('data-photo') !== key) return;
      el.style.backgroundImage = 'url("' + src + '")';
      el.classList.add('has-photo');
      if (el.classList.contains('wf-placeholder')) {
        el.setAttribute('role', 'img');
        el.setAttribute('aria-label', el.getAttribute('data-photo-alt') || el.textContent.trim() || 'Photo');
      }
    });
  }
  function scan(root) {
    if (root.nodeType !== 1) return;
    if (root.hasAttribute('data-photo')) apply(root);
    Array.prototype.forEach.call(root.querySelectorAll('[data-photo]'), apply);
  }

  document.addEventListener('DOMContentLoaded', function () {
    scan(document.body);
    /* Content rendered later (finder results, project cards, the project
       viewer) is picked up as it appears. */
    new MutationObserver(function (records) {
      records.forEach(function (r) {
        if (r.type === 'attributes') { r.target.removeAttribute('data-photo-done'); r.target.classList.remove('has-photo'); r.target.style.backgroundImage = ''; apply(r.target); }
        else Array.prototype.forEach.call(r.addedNodes, scan);
      });
    }).observe(document.body, { childList: true, subtree: true, attributes: true, attributeFilter: ['data-photo'] });
  });
})();
